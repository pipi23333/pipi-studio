const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const root = process.cwd();
  const server = http.createServer((req,res)=>{
    const name = new URL(req.url,'http://localhost').pathname;
    const file = path.join(root,name==='/'?'index.html':name.slice(1));
    if(!file.startsWith(root+path.sep)||!fs.existsSync(file)){res.writeHead(404);res.end();return;}
    res.setHeader('Content-Type',file.endsWith('.js')?'application/javascript':file.endsWith('.html')?'text/html; charset=utf-8':'application/octet-stream');
    fs.createReadStream(file).pipe(res);
  });
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  let browser;
  try {
    browser=await chromium.launch({headless:true});
    const context=await browser.newContext({viewport:{width:390,height:844}});
    const page=await context.newPage();
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    const base='http://127.0.0.1:'+server.address().port;
    await page.goto(base);
    assert(await page.locator('#languageGate').isVisible());
    assert(!(await page.locator('main').isVisible()));
    await page.locator('[data-language="zh"]').click();
    assert(!(await page.locator('#languageGate').isVisible()));
    assert.equal(await page.locator('html').getAttribute('lang'),'zh-CN');
    assert.match(await page.locator('h1').innerText(),/回忆/);
    await page.selectOption('#paletteMode','physical');
    await page.selectOption('#res','128');
    await page.selectOption('#size','60');
    assert(await page.locator('#exportPixel').isDisabled());
    assert.match(await page.locator('#pitch').innerText(),/直接耗材/);
    await page.locator('#physicalPalette').fill('#FFFFFF,#000000');
    await page.locator('#languageSwitch').click();
    await page.locator('[data-language="en"]').click();
    assert.equal(await page.locator('#physicalPalette').inputValue(),'#FFFFFF,#000000');
    assert.equal(await page.locator('#res').inputValue(),'128');
    assert.match(await page.locator('#pitch').innerText(),/direct filament/);
    assert(await page.locator('#exportPixel').isDisabled());
    await page.reload();
    assert(!(await page.locator('#languageGate').isVisible()));
    assert.equal(await page.locator('html').getAttribute('lang'),'en');
    await page.locator('a[href^="color-lab.html"]').click();
    assert.equal(await page.locator('html').getAttribute('lang'),'en');
    assert.match(await page.locator('#dbSummary').innerText(),/95 recipes/);
    await page.locator('#notes').fill('test note');
    await page.locator('#languageSwitch').click();
    await page.locator('[data-language="zh"]').click();
    assert.equal(await page.locator('#notes').inputValue(),'test note');
    assert.match(await page.locator('#dbSummary').innerText(),/95 种配方/);
    assert.match(await page.locator('#analyze').innerText(),/分析/);
    await page.locator('#analyze').click();
    assert.match(await page.locator('#stats').innerText(),/请选择图片/);
    await page.locator('#languageSwitch').click();
    await page.locator('[data-language="es"]').click();
    assert.match(await page.locator('#stats').innerText(),/Selecciona una imagen/);
    assert.deepEqual(errors,[]);
    console.log('Real Chromium smoke passed: language gate, mobile viewport, persistent preference, dynamic translation, page links and unchanged form state');
  } finally {if(browser)await browser.close();server.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
